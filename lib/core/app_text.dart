String translateAppText(String text, String languageCode) =>
    switch (languageCode) {
      'en' => _en[text] ?? text,
      'zh' => _zh[text] ?? text,
      _ => text,
    };

String appLocalizedText(String text) =>
    translateAppText(text, AppPreferences.locale.value.languageCode);

class Text extends m.StatelessWidget {
  final String? data;
  final m.InlineSpan? textSpan;
  final m.TextStyle? style;
  final m.StrutStyle? strutStyle;
  final m.TextAlign? textAlign;
  final m.TextDirection? textDirection;
  final m.Locale? locale;
  final bool? softWrap;
  final m.TextOverflow? overflow;
  final int? maxLines;
  final String? semanticsLabel;
  final m.TextWidthBasis? textWidthBasis;
  final m.TextHeightBehavior? textHeightBehavior;
  final m.Color? selectionColor;
  final m.TextScaler? textScaler;

  const Text(
    this.data, {
    super.key,
    this.style,
    this.strutStyle,
    this.textAlign,
    this.textDirection,
    this.locale,
    this.softWrap,
    this.overflow,
    this.maxLines,
    this.semanticsLabel,
    this.textWidthBasis,
    this.textHeightBehavior,
    this.selectionColor,
    this.textScaler,
  }) : textSpan = null;

  const Text.rich(
    this.textSpan, {
    super.key,
    this.style,
    this.strutStyle,
    this.textAlign,
    this.textDirection,
    this.locale,
    this.softWrap,
    this.overflow,
    this.maxLines,
    this.semanticsLabel,
    this.textWidthBasis,
    this.textHeightBehavior,
    this.selectionColor,
    this.textScaler,
  }) : data = null;

  @override
  m.Widget build(m.BuildContext context) => m.ValueListenableBuilder<m.Locale>(
    valueListenable: AppPreferences.locale,
    builder: (context, locale, _) => _buildText(locale.languageCode),
  );

  m.Widget _buildText(String languageCode) {
    final common = (
      style: style,
      strutStyle: strutStyle,
      textAlign: textAlign,
      textDirection: textDirection,
      locale: locale,
      softWrap: softWrap,
      overflow: overflow,
      maxLines: maxLines,
      semanticsLabel: semanticsLabel,
      textWidthBasis: textWidthBasis,
      textHeightBehavior: textHeightBehavior,
      selectionColor: selectionColor,
      textScaler: textScaler,
    );
    if (textSpan != null) {
      return m.Text.rich(
        textSpan!,
        style: common.style,
        strutStyle: common.strutStyle,
        textAlign: common.textAlign,
        textDirection: common.textDirection,
        locale: common.locale,
        softWrap: common.softWrap,
        overflow: common.overflow,
        maxLines: common.maxLines,
        semanticsLabel: common.semanticsLabel,
        textWidthBasis: common.textWidthBasis,
        textHeightBehavior: common.textHeightBehavior,
        selectionColor: common.selectionColor,
        textScaler: common.textScaler,
      );
    }
    return m.Text(
      translateAppText(data ?? '', languageCode),
      style: common.style,
      strutStyle: common.strutStyle,
      textAlign: common.textAlign,
      textDirection: common.textDirection,
      locale: common.locale,
      softWrap: common.softWrap,
      overflow: common.overflow,
      maxLines: common.maxLines,
      semanticsLabel: common.semanticsLabel,
      textWidthBasis: common.textWidthBasis,
      textHeightBehavior: common.textHeightBehavior,
      selectionColor: common.selectionColor,
      textScaler: common.textScaler,
    );
  }
}
